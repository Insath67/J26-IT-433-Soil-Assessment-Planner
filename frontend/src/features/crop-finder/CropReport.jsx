const FIELDS = [
  'N',
  'P',
  'K',
  'ph',
  'temperature',
  'humidity',
  'rainfall',
]

export default function CropReport({ result }) {
  const { t, i18n } = useTranslation('cropFinder')

  if (!result) return null

  const language = i18n.resolvedLanguage || 'en'
  const copy = COPY[language] || COPY.en
  const locale =
    language === 'si' ? 'si-LK' :
    language === 'ta' ? 'ta-LK' : 'en-LK'

  const number = (value, digits = 2) =>
    new Intl.NumberFormat(locale, {
      maximumFractionDigits: digits,
    }).format(value)

  const recommendations = result.recommendations || []
  const warnings = result.warnings || []

  return createPortal(
    <article className="crop-print-report" lang={language}>
      <header className="crop-report-heading">
        <strong lang="si">සරු බිම</strong>
        <span lang="en">SARU BIMA</span>
        <h1>{copy.title}</h1>
        <p>{t('district')} · {t('country')}</p>
      </header>

      <dl className="crop-report-meta">
        <dt>{copy.id}</dt>
        <dd>{result.analysis_id}</dd>
        <dt>{copy.date}</dt>
        <dd>{new Date(result.created_at).toLocaleString(locale)}</dd>
      </dl>

      <div className="crop-report-notice">
        <strong>{t('demo')}</strong>
        <p>{t('limitation')}</p>
      </div>

      <section>
        <h2>{copy.inputs}</h2>
        <table>
          <thead>
            <tr>
              <th>{copy.field}</th>
              <th>{copy.value}</th>
            </tr>
          </thead>
          <tbody>
            {FIELDS.map(field => (
              <tr key={field}>
                <td>{t(field)}</td>
                <td>
                  {result.inputs?.[field] == null
                    ? '—'
                    : number(result.inputs[field])}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
        <p className="crop-report-note">{t('unitsNote')}</p>
        <p className="crop-report-note">{t('rainNote')}</p>
      </section>

      <section>
        <h2>{copy.ranking}</h2>
        <table>
          <thead>
            <tr>
              <th>{copy.rank}</th>
              <th>{copy.crop}</th>
              <th>{copy.score}</th>
            </tr>
          </thead>
          <tbody>
            {recommendations.map((crop, index) => (
              <tr key={crop.crop}>
                <td>{index + 1}</td>
                <td>{t(crop.crop)}</td>
                <td>{number(crop.score_percent, 2)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <p className="crop-report-note">{t('shapNote')}</p>

      {recommendations.map(crop => (
        <section className="crop-report-shap" key={crop.crop}>
          <h2>{t(crop.crop)} — {copy.explanation}</h2>

          <table>
            <thead>
              <tr>
                <th>{copy.field}</th>
                <th>{copy.value}</th>
                <th>{copy.contribution}</th>
                <th>{copy.direction}</th>
              </tr>
            </thead>
            <tbody>
              {(crop.factors || []).map(factor => (
                <tr key={factor.feature}>
                  <td>{t(factor.feature)}</td>
                  <td>{number(factor.value)}</td>
                  <td>
                    {factor.shap_value > 0 ? '+' : ''}
                    {number(factor.shap_value, 5)}
                  </td>
                  <td>
                    {factor.shap_value > 0
                      ? copy.positive
                      : factor.shap_value < 0
                        ? copy.negative
                        : copy.neutral}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </section>
      ))}

      {warnings.length > 0 && (
        <section>
          <h2>{copy.warnings}</h2>
          <p>{copy.warningNote}</p>
          <ul>
            {warnings.map((warning, index) => (
              <li key={index} lang="en">
                {typeof warning === 'string'
                  ? warning
                  : JSON.stringify(warning)}
              </li>
            ))}
          </ul>
        </section>
      )}

      <footer className="crop-report-footer">
        {copy.footer}
      </footer>
    </article>,
    document.body,
  )
}